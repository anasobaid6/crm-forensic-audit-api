def detect_anomalies(df: pd.DataFrame) -> Dict[str, Any]:
    """
    Executes vectorized boolean masks across the entire DataFrame to isolate
    CRM data anomalies with zero row-by-row iteration bottlenecks.

    Returns a dictionary of masks, record counts, and impacted deal amounts.
    """
    n_rows = len(df)
    masks: Dict[str, pd.Series] = {}

    # 1. Duplicate Deals (Account + Stage + Close Date)
    # Marks duplicate occurrences that cause artificial pipeline inflation
    masks["duplicates"] = df.duplicated(
        subset=["account_name", "deal_stage", "close_date"],
        keep="first"
    )

    # 2. Amount Anomalies (Null, <= 0, or negative)
    numeric_amount = pd.to_numeric(df["amount"], errors="coerce")
    masks["amount_null"] = numeric_amount.isna()
    masks["amount_zero_or_negative"] = (~masks["amount_null"]) & (numeric_amount <= 0)
    masks["amount_invalid"] = masks["amount_null"] | masks["amount_zero_or_negative"]

    # 3. Stage & Date Logic Mismatches
    stage_series = df["deal_stage"].astype(str).str.strip().str.lower()
    close_dates_parsed = pd.to_datetime(df["close_date"], errors="coerce")
    
    # Condition A: Closed Won with missing/invalid close date
    won_missing_date = (stage_series == "closed won") & (df["close_date"].isna() | (df["close_date"].astype(str).str.strip() == ""))
    
    # Condition B: Open stage but close date has expired in the past (Zombie Pipeline)
    active_stages = ["discovery", "qualification", "proposal/quote", "negotiation/review"]
    is_active_stage = stage_series.isin(active_stages)
    is_expired_close_date = close_dates_parsed < REFERENCE_NOW
    zombie_deals = is_active_stage & is_expired_close_date

    masks["stage_mismatch"] = won_missing_date | zombie_deals

    # 4. Malformed Email Addresses
    email_series = df["contact_email"].astype(str).str.strip()
    masks["malformed_email"] = ~email_series.str.match(EMAIL_REGEX.pattern) | (email_series.isna()) | (email_series == "")

    # 5. Malformed Phone Numbers (< 7 digits or non-standard garbage)
    phone_series = df["contact_phone"].astype(str)
    digits_count = phone_series.str.replace(r"\D", "", regex=True).str.len()
    has_letters = phone_series.str.contains(r"[a-zA-Z]", regex=True)
    masks["malformed_phone"] = (digits_count < 7) | has_letters | (phone_series.isna()) | (phone_series == "")

    # 6. Unassigned Deal Owners
    owner_series = df["deal_owner"].astype(str).str.strip().str.lower()
    masks["unassigned_owner"] = (
        df["deal_owner"].isna() |
        owner_series.isin(["", "unassigned", "none", "tbd", "n/a", "nan"])
    )

    # 7. Corrupted UTF-8 Encodings (Mojibake)
    account_str = df["account_name"].astype(str)
    deal_name_str = df["deal_name"].astype(str)
    mojibake_pattern = r"(?:Ã©|Ã¼|Ã¶|Ã¤|Ã |Ã¨|Ã´|Ã®|Ã§|Ã±|Ã¸|Ã£|Ã|Â)"
    masks["corrupted_encoding"] = (
        account_str.str.contains(mojibake_pattern, regex=True) |
        deal_name_str.str.contains(mojibake_pattern, regex=True)
    )

    # 8. Non-standard Date Formats
    date_str = df["close_date"].astype(str).str.strip()
    is_not_iso = ~date_str.str.match(ISO_DATE_REGEX.pattern)
    has_date_content = (date_str != "") & (date_str.str.lower() != "nan")
    masks["non_standard_date"] = has_date_content & is_not_iso

    # Composite Corrupted Records (row has at least one significant anomaly)
    masks["any_critical_or_warning"] = (
        masks["duplicates"] |
        masks["amount_invalid"] |
        masks["stage_mismatch"] |
        masks["malformed_email"] |
        masks["malformed_phone"] |
        masks["unassigned_owner"]
    )

    return {
        "masks": masks,
        "numeric_amount": numeric_amount,
        "won_missing_date": won_missing_date,
        "zombie_deals": zombie_deals
    }


def calculate_revenue_at_risk(df: pd.DataFrame, detection_results: Dict[str, Any]) -> Tuple[float, float, float]:
    """
    Quantifies exact financial exposure caused by corrupted CRM pipeline data:
    1. Duplicated deal amount (artificial revenue double-counting)
    2. Negative deal values misstating real pipeline
    3. Zombie active deals past target close date (stale forecasting)
    4. Closed Won deals lacking close dates (unrecognized revenue)
    5. Orphaned deals without sales rep ownership
    """
    numeric_amount = detection_results["numeric_amount"]
    masks = detection_results["masks"]

    # Fill NaN amounts temporarily with 0 for monetary calculations
    safe_amount = numeric_amount.fillna(0.0)

    # Total Gross Pipeline
    valid_positive_amounts = safe_amount[safe_amount > 0]
    total_pipeline_value = float(valid_positive_amounts.sum())

    # Revenue At Risk Breakdown
    duplicate_risk = float(safe_amount[masks["duplicates"] & (safe_amount > 0)].sum())
    negative_impact = float(abs(safe_amount[safe_amount < 0].sum()))
    zombie_risk = float(safe_amount[detection_results["zombie_deals"] & (safe_amount > 0)].sum())
    won_missing_risk = float(safe_amount[detection_results["won_missing_date"] & (safe_amount > 0)].sum())
    orphan_risk = float(safe_amount[masks["unassigned_owner"] & (safe_amount > 0)].sum())

    # De-duplicated union mask for unique total revenue at risk (avoid double counting same dollar)
    risk_mask = (
        masks["duplicates"] |
        (safe_amount < 0) |
        detection_results["zombie_deals"] |
        detection_results["won_missing_date"]
    )
    total_revenue_at_risk = float(safe_amount[risk_mask & (safe_amount > 0)].sum()) + negative_impact

    # Percentage of pipeline at risk
    risk_percentage = round((total_revenue_at_risk / total_pipeline_value * 100) if total_pipeline_value > 0 else 0.0, 2)

    return total_pipeline_value, total_revenue_at_risk, risk_percentage


def calculate_hygiene_score(total_rows: int, masks: Dict[str, pd.Series]) -> float:
    """
    Computes an enterprise Data Health Score (0.0 to 100.0%) utilizing
    weighted penalty coefficients:
    - CRITICAL Severity (Weight: 40%): Duplicates, Corrupted Amounts, Stage Mismatches
    - WARNING Severity (Weight: 35%): Malformed Emails, Truncated Phones, Unassigned Owners
    - MINOR Severity (Weight: 25%): Non-standard dates, Encoding artifacts
    """
    if total_rows == 0:
        return 100.0

    # Severity error rates (bounded between 0.0 and 1.0)
    critical_errors = (
        masks["duplicates"].sum() +
        masks["amount_invalid"].sum() +
        masks["stage_mismatch"].sum()
    )
    warning_errors = (
        masks["malformed_email"].sum() +
        masks["malformed_phone"].sum() +
        masks["unassigned_owner"].sum()
    )
    minor_errors = (
        masks["corrupted_encoding"].sum() +
        masks["non_standard_date"].sum()
    )

    critical_penalty = min(critical_errors / (total_rows * 3.0), 1.0) * 40.0
    warning_penalty = min(warning_errors / (total_rows * 3.0), 1.0) * 35.0
    minor_penalty = min(minor_errors / (total_rows * 2.0), 1.0) * 25.0

    score = 100.0 - (critical_penalty + warning_penalty + minor_penalty)
    return round(max(0.0, min(100.0, score)), 2)


def generate_executive_summary(
    hygiene_score: float,
    total_pipeline: float,
    revenue_at_risk: float,
    risk_percentage: float,
    breakdown: AnomalyBreakdown
) -> ExecutiveSummary:
    """Synthesizes C-Suite level findings and tactical recommendations."""
    if hygiene_score >= 90:
        classification = "ENTERPRISE GRADE"
    elif hygiene_score >= 75:
        classification = "MODERATE"
    elif hygiene_score >= 50:
        classification = "NEEDS ATTENTION"
    else:
        classification = "CRITICAL RISK"

    # Identify primary monetary threat
    threats = [
        ("Duplicate Deals Inflating Forecasts", breakdown.duplicate_deals.monetary_impact_usd),
        ("Invalid/Missing Pipeline Amounts", breakdown.invalid_amounts.monetary_impact_usd),
        ("Zombie Deals & Unreconciled Stages", breakdown.stage_mismatches.monetary_impact_usd),
        ("Orphaned Deals Without Ownership", breakdown.unassigned_owners.monetary_impact_usd),
    ]
    primary_threat = max(threats, key=lambda x: x[1])[0]

    recommendations = [
        f"Execute automated deduplication to remove ${breakdown.duplicate_deals.monetary_impact_usd:,.2f} in fictitious pipeline.",
        f"Impute or review {breakdown.invalid_amounts.count:,} deals with missing/zero amounts to re-establish sales forecast fidelity.",
        f"Enforce automated stage-gate rules: Close or renew {breakdown.stage_mismatches.count:,} expired active deals.",
        f"Route {breakdown.unassigned_owners.count:,} unassigned accounts to Sales Ops routing queue to prevent SLA abandonment."
    ]

    projected_recovery = round(min(98.5, hygiene_score + (100.0 - hygiene_score) * 0.88), 1)

    return ExecutiveSummary(
        health_classification=classification,
        primary_revenue_threat=primary_threat,
        projected_recovery_percentage=projected_recovery,
        actionable_recommendations=recommendations
    )


def audit_dataframe(df: pd.DataFrame) -> AuditReportResponse:
    """
    Primary entrypoint for analyzing a CRM export in memory.
    Executes detection, risk valuation, hygiene scoring, and reporting in < 150ms.
    """
    start_time = datetime.now(timezone.utc)
    total_records = len(df)

    detection = detect_anomalies(df)
    masks = detection["masks"]
    numeric_amount = detection["numeric_amount"]
    safe_amount = numeric_amount.fillna(0.0)

    total_pipeline, revenue_at_risk, risk_percentage = calculate_revenue_at_risk(df, detection)
    hygiene_score = calculate_hygiene_score(total_records, masks)

    clean_records = int((~masks["any_critical_or_warning"]).sum())
    corrupted_records = total_records - clean_records

    # Construct Anomaly Breakdown
    breakdown = AnomalyBreakdown(
        duplicate_deals=AnomalyDetail(
            count=int(masks["duplicates"].sum()),
            monetary_impact_usd=round(float(safe_amount[masks["duplicates"] & (safe_amount > 0)].sum()), 2),
            severity="CRITICAL"
        ),
        invalid_amounts=AnomalyDetail(
            count=int(masks["amount_invalid"].sum()),
            monetary_impact_usd=round(float(abs(safe_amount[safe_amount < 0].sum())), 2),
            severity="CRITICAL"
        ),
        stage_mismatches=AnomalyDetail(
            count=int(masks["stage_mismatch"].sum()),
            monetary_impact_usd=round(float(safe_amount[masks["stage_mismatch"] & (safe_amount > 0)].sum()), 2),
            severity="CRITICAL"
        ),
        malformed_emails=AnomalyDetail(
            count=int(masks["malformed_email"].sum()),
            monetary_impact_usd=0.0,
            severity="WARNING"
        ),
        malformed_phones=AnomalyDetail(
            count=int(masks["malformed_phone"].sum()),
            monetary_impact_usd=0.0,
            severity="WARNING"
        ),
        unassigned_owners=AnomalyDetail(
            count=int(masks["unassigned_owner"].sum()),
            monetary_impact_usd=round(float(safe_amount[masks["unassigned_owner"] & (safe_amount > 0)].sum()), 2),
            severity="WARNING"
        ),
        corrupted_encodings=AnomalyDetail(
            count=int(masks["corrupted_encoding"].sum()),
            monetary_impact_usd=0.0,
            severity="MINOR"
        ),
        non_standard_dates=AnomalyDetail(
            count=int(masks["non_standard_date"].sum()),
            monetary_impact_usd=0.0,
            severity="MINOR"
        )
    )

    severity_counts = {
        "CRITICAL": int(breakdown.duplicate_deals.count + breakdown.invalid_amounts.count + breakdown.stage_mismatches.count),
        "WARNING": int(breakdown.malformed_emails.count + breakdown.malformed_phones.count + breakdown.unassigned_owners.count),
        "MINOR": int(breakdown.corrupted_encodings.count + breakdown.non_standard_dates.count)
    }

    exec_summary = generate_executive_summary(
        hygiene_score=hygiene_score,
        total_pipeline=total_pipeline,
        revenue_at_risk=revenue_at_risk,
        risk_percentage=risk_percentage,
        breakdown=breakdown
    )

    duration_ms = (datetime.now(timezone.utc) - start_time).total_seconds() * 1000.0

    return AuditReportResponse(
        hygiene_score=hygiene_score,
        total_records=total_records,
        clean_records=clean_records,
        corrupted_records=corrupted_records,
        total_pipeline_value=round(total_pipeline, 2),
        revenue_at_risk=round(revenue_at_risk, 2),
        risk_percentage=risk_percentage,
        anomalies_by_severity=severity_counts,
        anomaly_breakdown=breakdown,
        executive_summary=exec_summary,
        audit_timestamp=start_time,
        execution_time_ms=round(duration_ms, 2)
    )


def remediate_dataset(df: pd.DataFrame, config: RemediationConfig) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """
    Applies high-speed vectorized data cleaning and transformation pipeline:
    1. Deduplicates based on enterprise keys
    2. Imputes missing/negative deal amounts using cohort median
    3. Normalizes and repairs email addresses
    4. Standardizes phone numbers to clean E.164-compatible format
    5. Coerces all dates to ISO YYYY-MM-DD and aligns logic
    6. Repairs UTF-8 character encoding mojibake
    7. Routes unassigned owners to designated ops pool
    """
    clean_df = df.copy()
    stats: Dict[str, int] = {}
    original_count = len(clean_df)

    # 1. Deduplication
    if config.deduplicate:
        clean_df = clean_df.drop_duplicates(
            subset=["account_name", "deal_stage", "close_date"],
            keep="first"
        )
        stats["duplicates_removed"] = original_count - len(clean_df)

    # 2. Character Encoding Fix
    if config.fix_encoding:
        for bad_char, good_char in MOJIBAKE_MAP.items():
            clean_df["account_name"] = clean_df["account_name"].astype(str).str.replace(bad_char, good_char, regex=False)
            clean_df["deal_name"] = clean_df["deal_name"].astype(str).str.replace(bad_char, good_char, regex=False)
        stats["encodings_repaired"] = 1

    # 3. Deal Amount Imputation
    if config.impute_amounts:
        numeric_amt = pd.to_numeric(clean_df["amount"], errors="coerce")
        invalid_mask = numeric_amt.isna() | (numeric_amt <= 0)
        
        if config.imputation_strategy == "median":
            # Cohort median per stage
            stage_medians = clean_df.groupby("deal_stage")["amount"].transform(
                lambda s: pd.to_numeric(s, errors="coerce")[pd.to_numeric(s, errors="coerce") > 0].median()
            )
            global_median = numeric_amt[numeric_amt > 0].median()
            if math.isnan(global_median):
                global_median = 50000.0
            replacement_series = stage_medians.fillna(global_median)
        elif config.imputation_strategy == "mean":
            global_mean = numeric_amt[numeric_amt > 0].mean()
            replacement_series = pd.Series(global_mean if not math.isnan(global_mean) else 50000.0, index=clean_df.index)
        else:
            replacement_series = pd.Series(0.0, index=clean_df.index)

        clean_df.loc[invalid_mask, "amount"] = replacement_series[invalid_mask].round(2)
        stats["amounts_imputed"] = int(invalid_mask.sum())

    # 4. Email Sanitization
    if config.sanitize_emails:
        emails = clean_df["contact_email"].astype(str).str.strip().str.lower()
        # Clean double @@
        emails = emails.str.replace(r"@@+", "@", regex=True)
        # Remove trailing dot or spaces
        emails = emails.str.rstrip(".")
        clean_df["contact_email"] = emails
        stats["emails_sanitized"] = len(clean_df)

    # 5. Phone Normalization
    if config.normalize_phones:
        raw_phones = clean_df["contact_phone"].astype(str)
        # Strip all non-digit characters
        digits = raw_phones.str.replace(r"\D", "", regex=True)
        
        def format_phone(d: str) -> str:
            if len(d) == 10:
                return f"+1-{d[0:3]}-{d[3:6]}-{d[6:10]}"
            elif len(d) == 11 and d.startswith("1"):
                return f"+1-{d[1:4]}-{d[4:7]}-{d[7:11]}"
            elif len(d) >= 7:
                return f"+{d}"
            return "+1-000-000-0000"  # Flagged standard placeholder
            
        clean_df["contact_phone"] = digits.apply(format_phone)
        stats["phones_normalized"] = len(clean_df)

    # 6. Date Normalization & Logic Reconciliation
    if config.normalize_dates:
        parsed_dates = pd.to_datetime(clean_df["close_date"], errors="coerce")
        created_dates = pd.to_datetime(clean_df["created_at"], errors="coerce")
        
        # If Closed Won lacks close_date, set to created_at + 30 days or reference date
        if config.reconcile_stage_dates:
            stage_lower = clean_df["deal_stage"].astype(str).str.strip().str.lower()
            won_missing = (stage_lower == "closed won") & parsed_dates.isna()
            fallback_won_date = created_dates + pd.Timedelta(days=30)
            parsed_dates = parsed_dates.fillna(fallback_won_date).fillna(REFERENCE_NOW)

            # Active deals in the past: extend to +45 days from reference date
            active_expired = stage_lower.isin(["discovery", "qualification", "proposal/quote", "negotiation/review"]) & (parsed_dates < REFERENCE_NOW)
            parsed_dates.loc[active_expired] = REFERENCE_NOW + pd.Timedelta(days=45)

        clean_df["close_date"] = parsed_dates.dt.strftime("%Y-%m-%d").fillna(REFERENCE_NOW.strftime("%Y-%m-%d"))
        stats["dates_normalized"] = len(clean_df)

    # 7. Orphan Deal Owner Resolution
    if config.resolve_orphan_owners:
        owner_str = clean_df["deal_owner"].astype(str).str.strip()
        orphan_mask = (
            clean_df["deal_owner"].isna() |
            owner_str.str.lower().isin(["", "unassigned", "none", "tbd", "n/a", "nan"])
        )
        clean_df.loc[orphan_mask, "deal_owner"] = config.default_owner
        stats["orphans_reassigned"] = int(orphan_mask.sum())

    stats["final_record_count"] = len(clean_df)
    return clean_df, stats
